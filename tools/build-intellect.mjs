// Copies the Intellect theme's real CSS, JS and fonts into the prototype, writes the Zariva theme style's
// CSS variables (captured from Intellect rendering the Zariva style), and turns Intellect's icon snippet
// into a JS module. Run from prototype/: node tools/build-intellect.mjs
import fs from 'node:fs';
import path from 'node:path';

const THEME = path.resolve('../../THREE10/intellect');
const OUT = path.resolve('site/assets/intellect');
fs.mkdirSync(OUT, { recursive: true });

const files = [
  'base.css', 'content.css', 'sections.css', 'product.css', 'collection.css', 'cart.css', 'slideshow.css', 'pages.css', 'bundle.css',
  'core.js', 'motion.js', 'theme.js', 'cart.js', 'product.js', 'collection.js', 'slider.js', 'sections.js', 'reels.js', 'slideshow.js', 'bundle.js', 'cursor.js', 'vendor-lenis.js',
  'moments.js', 'moments.css', 'loupe.js', 'loupe.css', 'loupe-loader.js', 'archivo-latin.woff2', 'archivo-latin-italic.woff2',
];
for (const f of files) fs.copyFileSync(path.join(THEME, 'assets', f), path.join(OUT, f));

// Theme style variables, as Intellect rendered them for Zariva (tools/ref/parts/head-style.css).
let css = fs.readFileSync(path.resolve('tools/ref/parts/head-style.css'), 'utf8');
css = css.replace(/@font-face\s*\{[^}]*\/cdn\/fonts\/[^}]*\}/g, ''); // library fonts are unused in Intellect type
css = css.replace(/url\("[^"]*archivo-latin-italic\.woff2[^"]*"\)/g, 'url("archivo-latin-italic.woff2")');
css = css.replace(/url\("[^"]*archivo-latin\.woff2[^"]*"\)/g, 'url("archivo-latin.woff2")');
fs.writeFileSync(path.join(OUT, 'theme-vars.css'), `/* House of Zariva: Intellect theme style variables (generated by Intellect's theme-styles snippet). */\n${css}\n`);

// Icons: Intellect's snippets/icon.liquid as a lookup.
const liquid = fs.readFileSync(path.join(THEME, 'snippets/icon.liquid'), 'utf8');
const icons = {};
for (const m of liquid.matchAll(/\{%-?\s*when '([^']+)'(?:,\s*'([^']+)')?\s*-?%\}\s*(<svg[\s\S]*?<\/svg>)/g)) {
  const svg = m[3].replace('class="{{ cls }}"', 'class="icon icon-__NAME__"').replace('{{ stroke }}', 'fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"');
  icons[m[1]] = svg;
  if (m[2]) icons[m[2]] = svg;
}
fs.writeFileSync(path.resolve('site/assets/zariva/icons.js'), `// Intellect icons (snippets/icon.liquid). Generated by tools/build-intellect.mjs.\nconst ICONS = ${JSON.stringify(icons, null, 1)};\nexport const icon = (name, cls = '') => (ICONS[name] || '').replace('__NAME__', name + (cls ? ' ' + cls : ''));\n`);
console.log(`copied ${files.length} files, ${Object.keys(icons).length} icons`);
